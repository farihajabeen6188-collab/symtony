<?php

declare(strict_types=1);

namespace App\Application\TestLab;

use App\Application\Investigation\Analyzer\StaleCacheAnalyzer;
use App\Domain\Investigation\EvidenceItem;
use App\Domain\Investigation\Finding;
use App\Domain\Investigation\Investigation;

/**
 * Writes a regression test without a model, from a template keyed to a verified analyzer finding.
 * Every concrete value (SKU, cache key, customer token, helper method) is taken from the investigation's
 * evidence or from allow-listed source files — nothing is invented. Returns null when no template applies.
 */
final class TemplateTestWriter
{
    public function __construct(private readonly SourceContext $source)
    {
    }

    /**
     * @param list<Finding>               $findings
     * @param array<string, EvidenceItem> $evidence
     */
    public function write(Investigation $inv, array $findings, array $evidence): ?TestProposal
    {
        $stale = null;
        foreach ($findings as $f) {
            if ($f->isVerified() && StaleCacheAnalyzer::SOURCE === $f->getSource()) {
                $stale = $f;
                break;
            }
        }
        if (null === $stale) {
            return null;
        }

        $cacheKey = null;
        $cacheRef = null;
        $writeRef = null;
        foreach ($stale->getCitations() as $ref) {
            $item = $evidence[$ref] ?? null;
            if (null === $item) {
                continue;
            }
            $d = $item->getData();
            if (isset($d['cache_key'])) {
                $cacheKey = (string) $d['cache_key'];
                $cacheRef = $ref;
            } elseif ('context' === $item->getKind() && null === $writeRef) {
                $writeRef = $ref;
            }
        }
        if (null === $cacheKey || 1 !== preg_match('/(SKU-[A-Za-z0-9-]+)/', $cacheKey, $m)) {
            return null;
        }
        $sku = $m[1];

        // What the shop's test harness and auth actually provide (allow-listed files only).
        $base = (string) $this->source->config('base_class');
        $harness = (string) $this->source->read('tests/ShopTestCase.php');
        $payments = (string) $this->source->read('tests/Support/MockPaymentApi.php');
        $auth = (string) $this->source->read('src/Security/CustomerAuthenticator.php');
        $this->source->read('src/Inventory/InventoryService.php');
        $this->source->read('src/Catalog/ProductRepository.php');
        if (!str_contains($harness, 'function checkout(') || !str_contains($payments, 'public static array $requests') || 0 === (int) preg_match_all("/'(demo-customer-[a-z]+)'/", $auth, $tokens)) {
            return null;
        }
        $customer = $tokens[1][\count($tokens[1]) - 1];

        $incident = $inv->getIncident();
        $class = \sprintf('Sym%dStaleCacheCheckoutTest', $incident->getNumber());
        $namespace = (string) $this->source->config('test_namespace');
        $refs = implode(', ', $stale->getCitations());
        $code = <<<PHP
            <?php

            declare(strict_types=1);

            namespace {$namespace};

            use App\\Catalog\\ProductRepository;
            use App\\Inventory\\InventoryService;
            use App\\Tests\\Support\\MockPaymentApi;
            use {$base};

            /**
             * Regression test for {$incident->getReference()} (investigation {$inv->getShortId()}).
             * Evidence: {$refs}.
             * Generated by SYMTONY from a template (no language model). Review before running.
             */
            final class {$class} extends ShopTestCase
            {
                public function testCheckoutRejectsStockThatOnlyExistsInAStaleCache(): void
                {
                    \$container = static::getContainer();

                    // A shopper reads the stock: the value is cached ({$cacheRef}: cache hit {$cacheKey}).
                    \$container->get(InventoryService::class)->availableStock('{$sku}');

                    // The authoritative stock changes in the database without touching the cache ({$writeRef}).
                    \$container->get(ProductRepository::class)->setStock('{$sku}', 0);

                    \$this->checkout('{$customer}', '{$sku}', 1);

                    self::assertResponseStatusCodeSame(409, 'Missing stock must be rejected cleanly, not end in a 500.');
                    self::assertCount(0, MockPaymentApi::\$requests, 'No payment may be authorized for stock that does not exist.');
                }
            }

            PHP;

        return new TestProposal(
            title: 'Checkout must not use a stale cached stock level',
            purpose: \sprintf('Reproduces %s: a stock value cached before the database changed lets checkout authorize payment, then the write fails.', $incident->getReference()),
            preconditions: [\sprintf('%s has stock in the database and its stock level is cached.', $sku), 'The database stock drops to 0 without the cache being invalidated.'],
            scenario: \sprintf('Read stock for %s (caches it), set the database stock to 0, then check out 1 unit as %s.', $sku, $customer),
            expected: 'HTTP 409 and no call to the payment provider. On the buggy build this fails (HTTP 500 from the constraint violation).',
            className: $class,
            code: $code,
            citations: $stale->getCitations(),
            source: 'template:stale_cache',
        );
    }
}
